-- ============================================================
-- Live monitoring schema baseline
-- ============================================================
--
-- Codifies the 25-column `public.monitoring` table that was
-- created outside the migration history. Safe to run against
-- an existing table: CREATE / ADD COLUMN are idempotent and
-- existing column types are intentionally left unchanged.
--
-- Existing column types are not altered. The runtime drift
-- script (`npm run verify:monitoring`) and the app-side
-- monitoringSchema contract catch type/value drift.
--
-- RLS is intentionally NOT changed here. The prototype's open
-- `anon` update policy on `monitoring` is a separate security
-- task (see docs/implementation-plan/monitoring_history.md).
-- ============================================================

begin;

create table if not exists public.monitoring (
  monitor_id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,

  battery_level integer default 0,
  battery_status text default 'Idle',
  time_remaining text default '0h 00m',
  voltage numeric(10,2) default 0,
  watt_hours integer default 0,
  current_load numeric(10,2) default 0,
  device_status text default 'Offline',
  last_seen timestamptz,

  solar_input numeric(10,2) default 0,
  solar_status text default 'Low',
  solar_timer interval default '00:00:00',
  solar_voltage numeric(10,2) default 0,
  solar_current numeric(10,2) default 0,
  total_energy numeric(14,3) default 0,

  battery_temperature numeric(5,2) default 0,
  battery_temperature_status text default 'Nominal',
  dod_status text default 'Safe',

  solar_temperature numeric(5,2) default 0,
  solar_temperature_status text default 'Nominal',

  interior_temp numeric(5,2) default 0,
  interior_temp_status text default 'Nominal',

  cumulative_energy_input_wh numeric(14,3) default 0,
  cumulative_energy_output_wh numeric(14,3) default 0
);

