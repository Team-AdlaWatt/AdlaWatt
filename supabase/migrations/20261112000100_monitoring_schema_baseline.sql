-- ------------------------------------------------------------
-- Preflight: fail with a clear message before adding
-- constraints that would otherwise fail obscurely.
-- ------------------------------------------------------------

do $$
begin
  if exists (
    select 1
    from public.monitoring
    group by user_id
    having count(*) > 1
  ) then
    raise exception
      'public.monitoring has duplicate user_id values; resolve duplicates before applying the unique constraint';
  end if;

  if exists (
    select 1
    from public.monitoring
    where monitor_id is null
  ) then
    raise exception
      'public.monitoring has rows with null monitor_id; backfill them before adding the primary key';
  end if;

  if exists (
    select 1
    from public.monitoring
    group by monitor_id
    having count(*) > 1
  ) then
    raise exception
      'public.monitoring has duplicate monitor_id values; resolve duplicates before adding the primary key';
  end if;

  if exists (
    select 1
    from public.monitoring m
    left join auth.users u on u.id = m.user_id
    where u.id is null
  ) then
    raise exception
      'public.monitoring has user_id values that do not exist in auth.users; resolve orphans before adding the foreign key';
  end if;

  if exists (
    select 1
    from public.monitoring
    where battery_level < 0 or battery_level > 100
  ) then
    raise exception
      'public.monitoring has battery_level values outside 0..100';
  end if;
end $$;

-- ------------------------------------------------------------
-- Primary key / uniqueness / ownership
-- ------------------------------------------------------------

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conrelid = 'public.monitoring'::regclass
      and contype = 'p'
  ) then
    alter table public.monitoring
      add constraint monitoring_pkey
      primary key (monitor_id);
  end if;
end $$;

create unique index if not exists
  monitoring_user_id_key
  on public.monitoring (user_id);

do $$
begin
  if not exists (
    select 1
    from pg_constraint c
    join pg_attribute a
      on a.attrelid = c.conrelid
     and a.attnum = any (c.conkey)
    where c.conrelid = 'public.monitoring'::regclass
      and c.contype = 'f'
      and a.attname = 'user_id'
  ) then
    alter table public.monitoring
      add constraint monitoring_user_id_fkey
      foreign key (user_id)
      references auth.users(id)
      on delete cascade
      not valid;
  end if;
end $$;

do $$
begin
  if exists (
    select 1
    from pg_constraint
    where conrelid = 'public.monitoring'::regclass
      and conname = 'monitoring_user_id_fkey'
  ) then
    alter table public.monitoring
      validate constraint monitoring_user_id_fkey;
  end if;
end $$;

